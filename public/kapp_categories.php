/** 商品IDが入っている分野のslug（定義の順）。 */
function kapp_categories_of($id) {
    $out = array();
    foreach (kapp_categories() as $slug => $c) {
        if (in_array($id, $c['ids'], true)) { $out[] = $slug; }
    }
    return $out;
}

function kapp_category_url($slug) {
    return 'https://kappstore.exbridge.jp/c-' . rawurlencode($slug);   // フォルダを掘ると共通ヘッダーの相対リンクが壊れるので平らに
}
