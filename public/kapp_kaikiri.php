/** 導入キット（OSS 本体は同梱しない日本語化・導入手順の商品）かどうか */
function kapp_is_kit($app) {
    return (bool)preg_match('/導入(・運用)?キット|構築キット/u', (string)$app['name'] . (string)($app['seo_title'] ?? ''));
}

